import { useState } from "react";
import { api, type SpecPreview, type Workflow } from "../api";
import { PipelineGraph } from "../Graph";
import { go, toast } from "../lib";
import { IconBranch, IconGear, IconHourglass, IconMail, IconBolt, IconSpark } from "../ui";

type Mode = "text" | "yaml" | "json";

const SUGGESTIONS = [
  "When a webhook is received, if the amount is over $500, wait 1 day, then send a follow-up email.",
  "When a new user signs up, send a welcome email, wait 3 days, then send a reminder email.",
  "When a payment comes in over $2,000, call https://example.com/hook and then send a thank-you email.",
];

const EXAMPLE_YAML = `name: High-value order follow-up
on:
  if: amount > 500          # webhook trigger with a condition
steps:
  - id: score
    uses: score_order
    with: { amount: "\${{ trigger.amount }}" }
  - id: thanks
    email:
      to: "{{trigger.email}}"
      subject: "Thanks for order {{trigger.order_id}}"
      body: "Hi {{trigger.name}}, we got your order!"
  - wait: 1 day
  - if: steps.score.tier == "gold"
    email:
      to: "{{trigger.email}}"
      subject: "A gift for our VIPs"
      body: "Here is 10% off your next order."
`;

const EXAMPLE_JSON = JSON.stringify(
  {
    name: "Signup nurture",
    trigger: { event: "webhook" },
    steps: [
      { id: "welcome", type: "send_email", to: "{{trigger.email}}", subject: "Welcome!", body: "Welcome aboard, {{trigger.name}}!" },
      { id: "pause", type: "wait", duration: "2 days" },
      { id: "is_pro", type: "branch", condition: { field: "plan", op: "eq", value: "pro" }, then: "pro_tips", else: "upsell" },
      { id: "pro_tips", type: "send_email", to: "{{trigger.email}}", subject: "Pro tips", body: "Getting the most out of Pro…", next: "end" },
      { id: "upsell", type: "send_email", to: "{{trigger.email}}", subject: "Go Pro?", body: "Upgrade for more." },
    ],
  },
  null,
  2,
);

export function CreatePage({ onCreated }: { onCreated: (w: Workflow) => void }) {
  const [mode, setMode] = useState<Mode>("text");
  const [src, setSrc] = useState<Record<Mode, string>>({ text: SUGGESTIONS[0], yaml: EXAMPLE_YAML, json: EXAMPLE_JSON });
  const [preview, setPreview] = useState<SpecPreview | null>(null);
  const [note, setNote] = useState<string>("");
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState<"preview" | "save" | null>(null);

  const switchMode = (m: Mode) => {
    setMode(m);
    setPreview(null);
    setErr(null);
  };

  const doPreview = async () => {
    setBusy("preview");
    setErr(null);
    try {
      if (mode === "text") {
        const r = await api.fromText(src.text, false);
        setPreview(r.spec);
        setNote([r.generator === "claude" ? "Generated by Claude" : "Generated by the rule-based parser", ...r.notes].join(" · "));
      } else if (mode === "yaml") {
        const r = await api.fromYaml(src.yaml, false);
        setPreview(r.spec);
        setNote("Compiled from YAML");
      } else {
        const v = await api.validate(JSON.parse(src.json));
        if (!v.valid) throw new Error((v.errors ?? []).map((e) => `${(e.loc as unknown[] | undefined)?.join(".") ?? ""}: ${String(e.msg)}`).join("\n"));
        setPreview(v.spec!);
        setNote("Valid");
      }
    } catch (e) {
      setPreview(null);
      setErr((e as Error).message);
    } finally {
      setBusy(null);
    }
  };

  const save = async () => {
    setBusy("save");
    setErr(null);
    try {
      let wf: Workflow | null;
      if (mode === "yaml") wf = (await api.fromYaml(src.yaml, true)).workflow;
      else if (mode === "json") wf = await api.createWorkflow(JSON.parse(src.json));
      else wf = await api.createWorkflow(preview); // save exactly what was previewed
      if (!wf) throw new Error("not saved");
      onCreated(wf);
      toast("Workflow created");
      go(`/w/${wf.id}`);
    } catch (e) {
      setErr((e as Error).message);
    } finally {
      setBusy(null);
    }
  };

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <div className="crumbs"><a href="#/">Workflows</a> <span>/</span> <span style={{ color: "var(--ink)" }}>New</span></div>
          <h1>Create a workflow</h1>
          <p className="muted" style={{ marginTop: 6 }}>A trigger plus a chain of steps. Describe it, or write it as code.</p>
        </div>
        <div className="segmented">
          <button className={mode === "text" ? "active" : ""} onClick={() => switchMode("text")}>Describe it</button>
          <button className={mode === "yaml" ? "active" : ""} onClick={() => switchMode("yaml")}>YAML pipeline</button>
          <button className={mode === "json" ? "active" : ""} onClick={() => switchMode("json")}>JSON</button>
        </div>
      </div>

      <div className="grid-3">
        <div className="card">
          <div className="card-body stack" style={{ gap: 14 }}>
            {mode === "text" ? (
              <>
                <div className="prompt-box">
                  <textarea value={src.text} onChange={(e) => { setSrc({ ...src, text: e.target.value }); setPreview(null); }} placeholder="When … if … wait … then send an email …" />
                </div>
                <div className="suggestions">
                  {SUGGESTIONS.map((s) => (
                    <button key={s} onClick={() => { setSrc({ ...src, text: s }); setPreview(null); }}>{s.length > 60 ? s.slice(0, 58) + "…" : s}</button>
                  ))}
                </div>
              </>
            ) : (
              <div className="editor">
                <div className="editor-bar"><i /><i /><i /><span style={{ marginLeft: 8 }}>{mode === "yaml" ? "workflow.yml" : "workflow.json"}</span></div>
                <textarea value={src[mode]} spellCheck={false} onChange={(e) => { setSrc({ ...src, [mode]: e.target.value }); setPreview(null); }} />
              </div>
            )}
            <div className="row">
              <button className="btn" disabled={!!busy} onClick={doPreview}><IconSpark size={14} /> {busy === "preview" ? "Working…" : mode === "text" ? "Generate preview" : "Validate & preview"}</button>
              <button className="btn primary" disabled={!!busy || (mode === "text" && !preview)} onClick={save}>
                {busy === "save" ? "Saving…" : "Create workflow"}
              </button>
              {mode === "text" && !preview && <span className="muted small">Preview first, then create.</span>}
            </div>
            {err && <pre className="err-box mono">{err}</pre>}
          </div>
        </div>

        <div className="card">
          <div className="card-head"><h3>Building blocks</h3></div>
          <div className="card-body stack" style={{ gap: 14 }}>
            {[
              [<IconBolt key="b" size={15} />, "Webhook trigger", "Every workflow gets a URL. Optional conditions like amount > 500."],
              [<IconMail key="m" size={15} />, "Send email", "From your connected mailbox, with {{templates}}. Sent exactly once."],
              [<IconHourglass key="h" size={15} />, "Wait", "Minutes or days. Survives restarts; no server is held."],
              [<IconBranch key="br" size={15} />, "If / else", "Branch on any field from the trigger or earlier steps."],
              [<IconGear key="g" size={15} />, "Task", "HTTP request or built-in tasks (score_order, set, echo…)."],
            ].map(([icon, title, desc]) => (
              <div key={String(title)} className="row" style={{ alignItems: "flex-start", gap: 12 }}>
                <span className="gicon">{icon}</span>
                <div>
                  <div style={{ fontWeight: 600 }}>{title}</div>
                  <div className="muted small">{desc}</div>
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {preview && (
        <div className="card">
          <div className="card-head">
            <div>
              <h3>{preview.name}</h3>
              <div className="muted small" style={{ marginTop: 2 }}>{note}</div>
            </div>
            <button className="btn primary" disabled={!!busy} onClick={save}>{busy === "save" ? "Saving…" : "Create workflow"}</button>
          </div>
          <div className="card-body" style={{ paddingTop: 14, paddingBottom: 8 }}>
            <PipelineGraph trigger={preview.trigger} steps={preview.steps} />
          </div>
        </div>
      )}
    </div>
  );
}
